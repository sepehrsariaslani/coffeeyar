export function copyDemo(value) {
  return JSON.parse(JSON.stringify(value));
}

export function getDemoProducts(params = {}) {
  const requestedCategory = String(params.category_slug || "").trim();
  let items = DEMO_PRODUCTS.filter((item) => {
    if (!requestedCategory) return true;
    return item.category === requestedCategory || item.category_root === requestedCategory;
  });

  if (params.featured) items = items.filter((item) => item.is_featured);
  if (params.in_stock) items = items.filter((item) => item.stock_qty > 0);

  if (params.sort === "price_asc") {
    items = [...items].sort((a, b) => a.effective_price_toman - b.effective_price_toman);
  } else if (params.sort === "price_desc") {
    items = [...items].sort((a, b) => b.effective_price_toman - a.effective_price_toman);
  } else if (params.sort === "newest") {
    items = [...items].sort((a, b) => b.display_order - a.display_order);
  }

  const page = Math.max(Number(params.page) || 1, 1);
  const pageSize = Math.min(Math.max(Number(params.page_size) || 24, 1), 100);
  const start = (page - 1) * pageSize;

  return {
    items: copyDemo(items.slice(start, start + pageSize)),
    page,
    page_size: pageSize,
    total: items.length,
    has_next: start + pageSize < items.length,
  };
}

export function getDemoProduct(slug) {
  const item = DEMO_PRODUCTS.find((product) => product.slug === slug || product.id === slug);
  return item ? copyDemo(item) : null;
}

